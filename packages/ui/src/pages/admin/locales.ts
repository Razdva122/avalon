export function useAdminBotMessages() {
  const composer = useI18n({ useScope: 'global' });
  watch(
    composer.locale,
    (language) => {
      // Language loading replaces its global dictionary before committing the locale.
      composer.mergeLocaleMessage(language, { aiArena: messages[language as TLanguage] || messages.en });
    },
    { immediate: true },
  );
  return composer;
}
